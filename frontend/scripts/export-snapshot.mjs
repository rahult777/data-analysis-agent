/**
 * @typedef {object} ExportReport
 * @property {string} id
 * @property {string[]} kept the charts published, in chart_paths order
 * @property {string[]} hidden the charts left out (--hide)
 * @property {{ path: string, bytes: number }[]} dropped every key the projection leaves out, with its JSON size
 * @property {number} publishedHits always 0 (any hit fails the export)
 * @property {{ path: string, pattern: string, snippet: string }[]} droppedHits scan hits in the dropped fields (reported, not fatal)
 * @property {{ path: string, size: number, sha256: string }[]} files every file written, relative to snapshot/
 */

/**
 * @param {object} options
 * @param {string} options.id the analysis id (lowercase canonical UUID)
 * @param {URL | string} options.baseUrl the local backend (plain http on a loopback host)
 * @param {string[]} [options.hide] chart file names to leave out
 * @param {string} options.note the analysis's "About this example" note for the manifest (checked by checkNote)
 * @param {string} options.frontendDir the frontend/ folder to write snapshot/ into
 * @param {string} [options.plotlySha256] the pinned bundle (tests only)
 * @param {number} [options.plotlySize] the pinned bundle's size (tests only)
 * @param {number} [options.timeoutMs] per request
 * @param {(line: string) => void} [options.log]
 * @returns {Promise<ExportReport>}
 */
export async function exportSnapshot({
  id,
  baseUrl,
  hide = [],
  note,
  frontendDir,
  plotlySha256 = PLOTLY_SHA256,
  plotlySize = PLOTLY_SIZE,
  timeoutMs = 30_000,
  log = () => {},
}) {
  if (!CANONICAL_UUID.test(id)) throw new UsageError(`the analysis id must be a lowercase canonical UUID; got ${JSON.stringify(id)}`);
  const base = loopbackUrl(baseUrl);
  const noteProblems = checkNote(note, "the note");
  if (noteProblems.length > 0) throw new UsageError(`the note must be a valid About-this-example note:\n  - ${noteProblems.join("\n  - ")}`);
  const snapshotDir = path.join(frontendDir, SNAPSHOT_DIR);
  const tempDir = path.join(frontendDir, TEMP_DIR);
  for (const [dir, label] of [[snapshotDir, SNAPSHOT_DIR], [tempDir, TEMP_DIR]]) {
    if (fs.existsSync(dir)) throw new ExportError(`${label}/ already exists; the export never replaces or removes it`);
  }
  log(`export-snapshot: analysis ${id} from ${base.origin}`);

  // 1. The three routes.
  const status = await getJson(base, `/api/analysis/${id}/status`, CAP.status, timeoutMs);
  checkStatus(status, id);
  log("status: complete (no error, no pause)");
  const analysis = await getJson(base, `/api/analysis/${id}`, CAP.analysis, timeoutMs);
  if (!isPlainObject(analysis)) throw new ExportError("the analysis must be a JSON object");
  if (analysis.id !== id) throw new ExportError(`the analysis id must be ${id}; got ${JSON.stringify(analysis.id)}`);
  if (analysis.status !== "complete") throw new ExportError(`the analysis status must be "complete"; got ${JSON.stringify(analysis.status)}`);
  const chartPaths = analysis.chart_paths;
  if (!Array.isArray(chartPaths) || !chartPaths.every((name) => typeof name === "string")) {
    throw new ExportError("the analysis's chart_paths must be an array of file names");
  }
  const chartsRoute = await getJson(base, `/api/analysis/${id}/charts`, CAP.charts, timeoutMs);
  if (!isPlainObject(chartsRoute) || Object.keys(chartsRoute).join(",") !== "chart_paths") {
    throw new ExportError(`the charts route keys must be exactly chart_paths; got ${JSON.stringify(isPlainObject(chartsRoute) ? Object.keys(chartsRoute) : chartsRoute)}`);
  }
  if (JSON.stringify(chartsRoute.chart_paths) !== JSON.stringify(chartPaths)) {
    throw new ExportError("the charts route does not match the analysis's chart_paths");
  }
  log(`chart_paths: ${chartPaths.length} (the charts route agrees)`);

  // 2. Hidden charts, then the projection.
  for (const name of hide) {
    if (!chartPaths.includes(name)) throw new ExportError(`--hide ${name} is not one of the analysis's charts`);
  }
  const kept = chartPaths.filter((name) => !hide.includes(name));
  const published = projectPublished({ ...analysis, chart_paths: kept });
  const dropped = unpublishedEntries(analysis).map((entry) => ({ path: entry.path, bytes: jsonBytes(entry.value), value: entry.value }));
  log(`kept charts (${kept.length}): ${kept.join(", ")}`);
  log(`hidden charts (${hide.length}): ${hide.join(", ") || "none"}`);
  log(`dropped keys (${dropped.length}):`);
  for (const entry of dropped) log(`  ${String(entry.bytes).padStart(8)} B  ${entry.path}`);

  // 3. In memory, before anything is written: the build's rules, the exact
  // scan and the hidden-chart references.
  const analysisJson = `${JSON.stringify(published, null, 2)}\n`;
  /** @type {string[]} */
  const problems = [
    ...checkAnalysis(published, id),
    ...findForbiddenKeys(published),
    ...findForeignUuids(analysisJson, id).map((uuid) => `analyses/${id}.json would contain a UUID other than its own id: ${uuid}`),
    ...scanValue(published, "").map((hit) => `${hit.path || "(top level)"}: ${hit.pattern}: ${hit.snippet}`),
    ...hiddenReferences(published, hide),
  ];
  if (problems.length > 0) throw new ExportError(`the published projection fails ${problems.length} check(s):\n${problems.map((p) => `  - ${p}`).join("\n")}`);
  log(`published projection: ${Buffer.byteLength(analysisJson)} B; scan: 0 hits`);

  const droppedHits = dropped.flatMap((entry) => [
    ...scanValue(entry.value, entry.path),
    ...findForbiddenKeys({ [entry.path.split(/[.[]/).pop() ?? ""]: entry.value }).map((p) => ({ path: entry.path, pattern: "forbidden key", snippet: p })),
    ...findForeignUuids(JSON.stringify(entry.value) ?? "", id).map((uuid) => ({ path: entry.path, pattern: "foreign UUID", snippet: uuid })),
  ]);
  log(`dropped fields scan: ${droppedHits.length} hit(s) (not published)`);
  for (const hit of droppedHits) log(`  ${hit.path}: ${hit.pattern}: ${hit.snippet}`);

  // 4. The chart files and the shared bundle.
  /** @type {[string, Buffer][]} */
  const charts = [];
  for (const name of kept) {
    const isHtml = name.endsWith(".html");
    const bytes = await get(base, `/charts/${encodeURIComponent(name)}`, {
      cap: isHtml ? CAP.html : CAP.png,
      type: isHtml ? /^text\/html\b/i : /^image\/png\b/i,
      timeoutMs,
    });
    checkChart(name, bytes, id);
    charts.push([name, bytes]);
  }
  if (kept.some((name) => name.endsWith(".html"))) {
    const bytes = await get(base, `/charts/${PLOTLY}`, { cap: CAP.plotly, type: /^(?:text|application)\/javascript\b/i, timeoutMs });
    if (bytes.length !== plotlySize || sha256(bytes) !== plotlySha256 || !isPlotlyBundle(bytes.toString("latin1"))) {
      throw new ExportError(`${PLOTLY} is not the pinned bundle (expected ${plotlySize} bytes, sha256 ${plotlySha256}; got ${bytes.length} bytes, sha256 ${sha256(bytes)})`);
    }
    if (findForeignUuids(bytes.toString("latin1"), null).length > 0) throw new ExportError(`${PLOTLY} contains a UUID`);
    charts.push([PLOTLY, bytes]);
  }

  // 5. Write the temporary folder (exclusively), validate it with the build's
  // own reader, then move it into place.
  fs.mkdirSync(tempDir);
  fs.mkdirSync(path.join(tempDir, "analyses"));
  fs.mkdirSync(path.join(tempDir, "charts"));
  /** @type {[string, string | Buffer][]} */
  const files = [
    ["manifest.json", manifestJson([{ id, note }])],
    [`analyses/${id}.json`, analysisJson],
    ...charts.map(([name, bytes]) => /** @type {[string, Buffer]} */ ([`charts/${name}`, bytes])),
  ];
  for (const [rel, content] of files) fs.writeFileSync(path.join(tempDir, rel), content, { flag: "wx" });
  let snapshot;
  try {
    snapshot = readSnapshot(frontendDir, { SNAPSHOT_DIR: TEMP_DIR });
  } catch (error) {
    throw new ExportError(`the written snapshot fails the build's rules; it stays in ${TEMP_DIR}/ for inspection (remove it before the next run): ${error instanceof Error ? error.message : String(error)}`);
  }
  const expectPlotly = kept.some((name) => name.endsWith(".html"));
  if (
    JSON.stringify(snapshot.ids) !== JSON.stringify([id]) ||
    JSON.stringify(Object.keys(snapshot.notes)) !== JSON.stringify([id]) ||
    snapshot.notes[id] !== note ||
    JSON.stringify(snapshot.charts) !== JSON.stringify(kept) ||
    snapshot.plotly !== expectPlotly
  ) {
    throw new ExportError(`the written snapshot in ${TEMP_DIR}/ does not read back as written; it stays there for inspection`);
  }
  log(`note: ${JSON.stringify(note)}`);
  if (fs.existsSync(snapshotDir)) throw new ExportError(`${SNAPSHOT_DIR}/ appeared during the export; the new one stays in ${TEMP_DIR}/`);
  fs.renameSync(tempDir, snapshotDir);

  // 6. Report every file as it now is.
  const written = files.map(([rel]) => {
    const bytes = fs.readFileSync(path.join(snapshotDir, rel));
    return { path: rel, size: bytes.length, sha256: sha256(bytes) };
  });
  log(`written into ${SNAPSHOT_DIR}/:`);
  for (const file of written) log(`  ${file.sha256}  ${String(file.size).padStart(8)}  ${file.path}`);
  log(`total: ${written.length} files, ${written.reduce((sum, file) => sum + file.size, 0)} B`);

  return {
    id,
    kept,
    hidden: [...hide],
    dropped: dropped.map((entry) => ({ path: entry.path, bytes: entry.bytes })),
    publishedHits: 0,
    droppedHits,
    files: written,
  };
}

/**
 * @param {unknown} status
 * @param {string} id
 */
function checkStatus(status, id) {
  if (!isPlainObject(status)) throw new ExportError("the status route must return a JSON object");
  const keys = Object.keys(status).sort();
  if (keys.join(",") !== [...STATUS_KEYS].sort().join(",")) {
    throw new ExportError(`the status route keys must be exactly ${STATUS_KEYS.join(", ")}; got ${keys.join(", ")}`);
  }
  /** @type {[string, unknown, string][]} */
  const expected = [
    ["analysis_id", id, id],
    ["status", "complete", '"complete"'],
    ["current_agent", null, "null"],
    ["progress_pct", 100, "100"],
    ["error_message", null, "null"],
    ["pause_data", null, "null"],
  ];
  for (const [key, value, shown] of expected) {
    if (status[key] !== value) throw new ExportError(`the status route's ${key} must be ${shown}; got ${JSON.stringify(status[key])}`);
  }
}

/**
 * @param {string} name
 * @param {Buffer} bytes
 * @param {string} id
 */
function checkChart(name, bytes, id) {
  if (name.endsWith(".png")) {
    if (!bytes.subarray(0, PNG_SIGNATURE.length).equals(PNG_SIGNATURE)) throw new ExportError(`${name}: no PNG signature`);
    return;
  }
  const text = bytes.toString("latin1");
  if (!text.includes(SHARED_TAG)) throw new ExportError(`${name}: does not load the shared plotly.min.js (${SHARED_TAG})`);
  if (text.includes("plotly.js v")) throw new ExportError(`${name}: inlines plotly; charts must load the shared bundle`);
  const foreign = findForeignUuids(text, id);
  if (foreign.length > 0) throw new ExportError(`${name}: contains a UUID other than its analysis id: ${foreign.join(", ")}`);
}

/**
 * A kept field naming a hidden chart, by its file name or its stem.
 * @param {unknown} published
 * @param {string[]} hide
 * @returns {string[]}
 */
function hiddenReferences(published, hide) {
  const needles = hide.flatMap((name) => [name, name.replace(/\.(?:png|html)$/, "")]);
  return strings(published, "").flatMap(({ path: where, text }) =>
    hide.filter((name, i) => text.includes(needles[2 * i]) || text.includes(needles[2 * i + 1])).map((name) => `${where || "(top level)"} references the hidden chart ${name}`),
  );
}

/** @param {unknown} value */
function jsonBytes(value) {
  return Buffer.byteLength(JSON.stringify(value) ?? "null");
}

/** @param {Buffer | string} data */
function sha256(data) {
  return crypto.createHash("sha256").update(data).digest("hex");
}

/**
 * @param {unknown} value
 * @returns {value is Record<string, unknown>}
 */
function isPlainObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

// ---------------------------------------------------------------------------
// Command line
// ---------------------------------------------------------------------------

const FRONTEND = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** @param {string[]} argv */
async function main(argv) {
  let args;
  let note;
  try {
    args = parseArgs(argv);
    note = readNoteFile(args.noteFile);
  } catch (error) {
    if (!(error instanceof UsageError)) throw error;
    console.error(`export-snapshot: ${error.message}\n${USAGE}`);
    process.exit(2);
  }
  try {
    await exportSnapshot({ ...args, note, frontendDir: FRONTEND, log: (line) => console.log(line) });
  } catch (error) {
    // exportSnapshot's own usage errors come before any request or write.
    const usage = error instanceof UsageError;
    console.error(`export-snapshot: ${error instanceof Error ? error.message : String(error)}${usage ? `\n${USAGE}` : ""}`);
    process.exit(usage ? 2 : 1);
  }
}

// Run only as a script, not when imported by the tests (compared as real
// paths: the tests' temporary folders sit behind symlinks on macOS).
const invoked = process.argv[1] ? pathToFileURL(fs.realpathSync(process.argv[1])).href : "";
if (invoked === import.meta.url) await main(process.argv.slice(2));

// Exports one saved analysis into frontend/snapshot/, the data the public
// build (`npm run build:public`) renders (M2b.3a). It reads only the public
// GET routes of the owner's local backend, started read-only on a loopback
// address, and the chart files under /charts/. It publishes exactly what the
// page renders: the analysis is projected through the published key set in
// lib/snapshot-rules.mjs (PUBLISHED), the same definition the build validates
// against, and the charts named with --hide are left out.
//
// Usage, in frontend/:
//   node scripts/export-snapshot.mjs <analysis id> <base url> --note-file <path> [--hide <chart file name>]...
// e.g. node scripts/export-snapshot.mjs 77faa166-… http://127.0.0.1:8000 --note-file <note.txt> --hide <id>_barchart_customer_id.png
// The note file holds the analysis's "About this example" note for the
// manifest: one line of UTF-8 (one trailing newline is dropped) that passes the
// rules' checkNote. Usage errors, the note file's included, exit 2 before any
// request or write.
//
// Fail-closed: every response and file is checked before anything is
// written; the projection must pass the build's own rules and an exact scan
// (paths, URLs, emails, key-like strings, hosts, foreign UUIDs, forbidden
// keys) with zero hits, while hits in the dropped fields are reported. It
// writes into frontend/.snapshot-export/ (gitignored), validates that with
// readSnapshot, then moves it to frontend/snapshot/. It never replaces an
// existing snapshot and never deletes anything: after a failure past the
// first write the temporary folder stays, for inspection. It reads no
// environment variable and holds no secret.

import crypto from "node:crypto";
import fs from "node:fs";
import http from "node:http";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  checkAnalysis,
  checkNote,
  findForbiddenKeys,
  findForeignUuids,
  isPlotlyBundle,
  projectPublished,
  readSnapshot,
  scanText,
  unpublishedEntries,
} from "../lib/snapshot-rules.mjs";

export const USAGE = "Usage: node scripts/export-snapshot.mjs <analysis id> <base url> --note-file <path> [--hide <chart file name>]...";

// The shared plotly bundle the HTML charts load: plotly.js 2.30.0, as plotly
// 5.20.0 writes it (decisions.md 2026-10-12). After a plotly upgrade the
// bundle is regenerated by hand and these change with it (tasks.md, M2c).
export const PLOTLY_SHA256 = "3baddf12a4f47ac22f006078f95c38b21abd53d1511b80e600a60cf0c52bab6e";
export const PLOTLY_SIZE = 3620780;

export const TEMP_DIR = ".snapshot-export";
const SNAPSHOT_DIR = "snapshot";
const PLOTLY = "plotly.min.js";
const SHARED_TAG = '<script charset="utf-8" src="plotly.min.js"></script>';
const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const CANONICAL_UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const CHART_NAME = /^[\p{L}\p{N}_][\p{L}\p{N}_-]*\.(?:png|html)$/u;
const LOOPBACK_HOSTS = ["127.0.0.1", "localhost", "[::1]"];
const STATUS_KEYS = ["analysis_id", "status", "current_agent", "progress_pct", "error_message", "pause_data"];

const KiB = 1024;
// Byte caps per response; a body over its cap is refused.
const CAP = {
  status: 16 * KiB,
  analysis: 2 * KiB * KiB,
  charts: 64 * KiB,
  png: 2 * KiB * KiB,
  html: 50 * KiB - 1, // an HTML chart loads the shared bundle: it is small
  plotly: 4 * KiB * KiB,
};

export class UsageError extends Error {
  /** @param {string} message */
  constructor(message) {
    super(message);
    this.name = "UsageError";
  }
}

export class ExportError extends Error {
  /** @param {string} message */
  constructor(message) {
    super(message);
    this.name = "ExportError";
  }
}


/**
 * @param {string[]} argv the arguments after the script name
 * @returns {{ id: string, baseUrl: URL, hide: string[], noteFile: string }}
 */
export function parseArgs(argv) {
  /** @type {string[]} */
  const positional = [];
  /** @type {string[]} */
  const hide = [];
  /** @type {string | undefined} */
  let noteFile;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--hide") {
      const name = argv[i + 1];
      if (name === undefined) throw new UsageError("--hide needs a chart file name");
      if (!CHART_NAME.test(name)) throw new UsageError(`--hide ${JSON.stringify(name)} is not a chart file name (a plain .png or .html name)`);
      if (hide.includes(name)) throw new UsageError(`--hide ${name} is given twice`);
      hide.push(name);
      i += 1;
    } else if (arg === "--note-file") {
      const file = argv[i + 1];
      if (file === undefined) throw new UsageError("--note-file needs a path");
      if (file.startsWith("-")) throw new UsageError(`--note-file needs a path; got ${JSON.stringify(file)}`);
      if (noteFile !== undefined) throw new UsageError("--note-file is given twice");
      noteFile = file;
      i += 1;
    } else if (arg.startsWith("-")) {
      throw new UsageError(`unknown option ${JSON.stringify(arg)}`);
    } else {
      positional.push(arg);
    }
  }
  if (positional.length !== 2) throw new UsageError(`expected an analysis id and a base URL; got ${positional.length} argument(s)`);
  const [id, base] = positional;
  if (!CANONICAL_UUID.test(id)) throw new UsageError(`the analysis id must be a lowercase canonical UUID; got ${JSON.stringify(id)}`);
  const baseUrl = loopbackUrl(base);
  if (noteFile === undefined) throw new UsageError("--note-file <path> is required (the About-this-example note for the manifest)");
  return { id, baseUrl, hide, noteFile };
}

/**
 * The analysis's "About this example" note, read from a UTF-8 file: exactly
 * one trailing newline (LF or CRLF) is dropped, and the rest must pass the
 * rules' checkNote.
 * @param {string} file
 * @returns {string}
 */
export function readNoteFile(file) {
  let bytes;
  try {
    bytes = fs.readFileSync(file);
  } catch (error) {
    throw new UsageError(`--note-file ${file}: cannot be read (${/** @type {NodeJS.ErrnoException} */ (error).code ?? "error"})`);
  }
  let text;
  try {
    // Strict UTF-8; a leading byte order mark is dropped (ignoreBOM defaults to false).
    text = new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    throw new UsageError(`--note-file ${file}: not valid UTF-8`);
  }
  const note = text.endsWith("\r\n") ? text.slice(0, -2) : text.endsWith("\n") ? text.slice(0, -1) : text;
  const problems = checkNote(note, "the note");
  if (problems.length > 0) throw new UsageError(`--note-file ${file}:\n  - ${problems.join("\n  - ")}`);
  return note;
}

/**
 * manifest.json's bytes: each entry's id and note, as two-space JSON with a
 * final newline. The one serializer: the export writes the manifest with it,
 * and so was the committed manifest, so a re-export reproduces it.
 * @param {{ id: string, note?: string }[]} entries
 * @returns {string}
 */
export function manifestJson(entries) {
  return `${JSON.stringify({ analyses: entries.map(({ id, note }) => ({ id, note })) }, null, 2)}\n`;
}

/**
 * Plain http on a loopback host, with nothing but an optional port.
 * @param {string | URL} value
 * @returns {URL}
 */
function loopbackUrl(value) {
  let url;
  try {
    url = new URL(String(value));
  } catch {
    throw new UsageError(`the base URL is not a URL: ${JSON.stringify(String(value))}`);
  }
  const problems = [];
  if (url.protocol !== "http:") problems.push("use http:");
  if (!LOOPBACK_HOSTS.includes(url.hostname)) problems.push(`use a loopback host (${LOOPBACK_HOSTS.join(", ")})`);
  if (url.username || url.password) problems.push("no credentials");
  if (url.pathname !== "/" || url.search || url.hash) problems.push("no path, query or fragment");
  if (problems.length > 0) throw new UsageError(`the base URL must be the local backend's address (${problems.join("; ")}); got ${JSON.stringify(String(value))}`);
  return url;
}

// ---------------------------------------------------------------------------
// The scan (the patterns and scanText live in lib/snapshot-rules.mjs)
// ---------------------------------------------------------------------------

/**
 * The scan over every key and string of a value; a key's hits are reported
 * at the path of the object that holds it.
 * @param {unknown} value
 * @param {string} where
 * @returns {{ path: string, pattern: string, snippet: string }[]}
 */
function scanValue(value, where) {
  if (typeof value === "string") return scanText(value).map((hit) => ({ path: where, pattern: hit.pattern, snippet: snippet(value, hit.index) }));
  if (Array.isArray(value)) return value.flatMap((item, i) => scanValue(item, `${where}[${i}]`));
  if (typeof value !== "object" || value === null) return [];
  return Object.entries(value).flatMap(([key, child]) => [
    ...scanText(key).map((hit) => ({ path: where, pattern: `${hit.pattern} (in a key)`, snippet: snippet(key, hit.index) })),
    ...scanValue(child, where === "" ? key : `${where}.${key}`),
  ]);
}

/**
 * Every string inside a value, with its path.
 * @param {unknown} value
 * @param {string} where
 * @returns {{ path: string, text: string }[]}
 */
function strings(value, where) {
  if (typeof value === "string") return [{ path: where, text: value }];
  if (Array.isArray(value)) return value.flatMap((item, i) => strings(item, `${where}[${i}]`));
  if (typeof value !== "object" || value === null) return [];
  return Object.entries(value).flatMap(([key, child]) => [{ path: where, text: key }, ...strings(child, where === "" ? key : `${where}.${key}`)]);
}

/**
 * @param {string} text
 * @param {number} index
 */
function snippet(text, index) {
  return JSON.stringify(text.slice(Math.max(0, index - 20), index + 40));
}

// ---------------------------------------------------------------------------
// HTTP: GET only, loopback only, no redirects, a deadline and a byte cap
// ---------------------------------------------------------------------------

/**
 * @param {URL} baseUrl
 * @param {string} route
 * @param {{ cap: number, type: RegExp, timeoutMs: number }} options
 * @returns {Promise<Buffer>}
 */
function get(baseUrl, route, { cap, type, timeoutMs }) {
  const url = new URL(route, baseUrl);
  return new Promise((resolve, reject) => {
    let settled = false;
    /** @type {import("node:http").ClientRequest} */
    let request;
    // Settles once; a refusal also ends the request (a body that was cut off
    // must never resolve as if it were complete).
    /** @param {string} message */
    const refuse = (message) => {
      if (settled) return;
      settled = true;
      reject(new ExportError(`GET ${route}: ${message}`));
      request.destroy();
    };
    request = http.get(url, { agent: false, timeout: timeoutMs, headers: { accept: "*/*" } }, (response) => {
      const status = response.statusCode ?? 0;
      if (status !== 200) return refuse(status >= 300 && status < 400 ? `HTTP ${status}: redirects are refused` : `HTTP ${status}`);
      const contentType = String(response.headers["content-type"] ?? "");
      if (!type.test(contentType)) return refuse(`content type ${JSON.stringify(contentType)}, not ${type.source}`);
      const declared = Number(response.headers["content-length"]);
      if (Number.isFinite(declared) && declared > cap) return refuse(`the body (${declared} bytes declared) is over its ${cap}-byte cap`);
      /** @type {Buffer[]} */
      const chunks = [];
      let size = 0;
      response.on("data", (chunk) => {
        size += chunk.length;
        if (size > cap) refuse(`the body is over its ${cap}-byte cap`);
        else chunks.push(chunk);
      });
      response.on("end", () => {
        if (settled) return;
        settled = true;
        resolve(Buffer.concat(chunks));
      });
      response.on("error", (error) => refuse(error.message));
    });
    const deadline = setTimeout(() => refuse(`timed out after ${timeoutMs} ms`), timeoutMs);
    request.on("timeout", () => refuse(`timed out after ${timeoutMs} ms`));
    request.on("close", () => clearTimeout(deadline));
    request.on("error", (error) => refuse(error.message));
  });
}

/**
 * @param {URL} baseUrl
 * @param {string} route
 * @param {number} cap
 * @param {number} timeoutMs
 * @returns {Promise<unknown>}
 */
async function getJson(baseUrl, route, cap, timeoutMs) {
  const body = await get(baseUrl, route, { cap, type: /^application\/json\b/i, timeoutMs });
  try {
    return JSON.parse(body.toString("utf8"));
  } catch {
    throw new ExportError(`GET ${route}: the body is not valid JSON`);
  }
}

